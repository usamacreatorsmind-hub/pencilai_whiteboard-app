import 'package:flutter/material.dart';

class ChemicalElement {
  final int atomicNumber;
  final String symbol;
  final String name;
  final String atomicMass;
  final String category;
  final int period;
  final int group;
  final String electronConfiguration;
  final String state;

  const ChemicalElement({
    required this.atomicNumber,
    required this.symbol,
    required this.name,
    required this.atomicMass,
    required this.category,
    required this.period,
    required this.group,
    required this.electronConfiguration,
    required this.state,
  });

  Color get categoryColor => getCategoryColor(category);

  static Color getCategoryColor(String category) {
    switch (category) {
      case 'Alkali Metal':
        return const Color(0xFFEF4444); // Red
      case 'Alkaline Earth Metal':
        return const Color(0xFFF97316); // Orange
      case 'Transition Metal':
        return const Color(0xFFF59E0B); // Amber / Gold
      case 'Post-Transition Metal':
        return const Color(0xFF3B82F6); // Ocean Blue
      case 'Metalloid':
        return const Color(0xFF06B6D4); // Cyan
      case 'Reactive Nonmetal':
        return const Color(0xFF10B981); // Emerald Green
      case 'Noble Gas':
        return const Color(0xFF8B5CF6); // Purple / Violet
      case 'Lanthanide':
        return const Color(0xFFEC4899); // Pink
      case 'Actinide':
        return const Color(0xFFD946EF); // Fuchsia
      case 'Unknown':
      default:
        return const Color(0xFF64748B); // Slate
    }
  }

  static const List<String> categories = [
    'All',
    'Reactive Nonmetal',
    'Noble Gas',
    'Alkali Metal',
    'Alkaline Earth Metal',
    'Transition Metal',
    'Post-Transition Metal',
    'Metalloid',
    'Lanthanide',
    'Actinide',
    'Unknown',
  ];
}


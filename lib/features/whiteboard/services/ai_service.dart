import 'dart:async';
import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';
import 'package:http/http.dart' as http;

class AiService {
  AiService({
    http.Client? client,
    Duration requestTimeout = const Duration(seconds: 12),
    String? apiKey,
  }) : _client = client,
       _requestTimeout = requestTimeout,
       _apiKey = apiKey ?? AiService.apiKey;

  final http.Client? _client;
  final Duration _requestTimeout;
  final String _apiKey;

  static const String apiKey = String.fromEnvironment(
    'GEMINI_API_KEY',
    defaultValue: '',
  );
  static const List<String> _candidateModels = [
    'gemini-3.5-flash-lite',
    'gemini-3.5-flash',
    'gemini-flash-latest',
  ];

  /// Returns per-model OCR thinking configuration to prevent reasoning tokens
  /// from starving short OCR responses.
  static Map<String, dynamic>? _ocrThinkingConfigForModel(String model) {
    if (model.startsWith('gemini-2.5-flash')) {
      return const {'thinkingBudget': 0};
    }
    if (model.startsWith('gemini-3.5-')) {
      return const {'thinkingLevel': 'minimal'};
    }
    if (model.startsWith('gemini-3') || model.startsWith('gemini-flash')) {
      return const {'thinkingLevel': 'low'};
    }
    return null;
  }

  /// Returns true when [text] is an API/configuration error string generated by
  /// [AiService] rather than valid model output.
  static bool isErrorResponse(String text) {
    return text.startsWith('⚠️') ||
        text.startsWith('Error generating ') ||
        text.startsWith('Failed to generate ');
  }

  Future<String> _generate(
    String prompt,
    String label, {
    List<String>? imagePaths,
    List<Uint8List>? directBytes,
  }) async {
    if (_apiKey.trim().isEmpty) {
      return '⚠️ Gemini API Key is missing. Please run the app with --dart-define-from-file=env.json.';
    }

    List<Map<String, dynamic>> parts = [
      {'text': prompt},
    ];

    // Direct in-memory image bytes (instant, zero disk I/O)
    if (directBytes != null && directBytes.isNotEmpty) {
      for (var bytes in directBytes) {
        final base64Image = base64Encode(bytes);
        parts.add({
          'inline_data': {'mime_type': 'image/png', 'data': base64Image},
        });
      }
    }

    // Convert local slide image files to Base64 so Gemini can read visual slides
    if (imagePaths != null && imagePaths.isNotEmpty) {
      for (var path in imagePaths) {
        try {
          final file = File(path);
          if (await file.exists()) {
            final bytes = await file.readAsBytes();
            final base64Image = base64Encode(bytes);
            String mimeType = 'image/png';
            if (path.endsWith('.jpg') || path.endsWith('.jpeg')) {
              mimeType = 'image/jpeg';
            }
            parts.add({
              'inline_data': {'mime_type': mimeType, 'data': base64Image},
            });
          }
        } catch (_) {}
      }
    }

    final isOcr = label == 'Handwriting OCR';
    final bool useBoundedOcr =
        isOcr && _requestTimeout >= const Duration(seconds: 6);
    final Duration totalBudget = useBoundedOcr
        ? const Duration(seconds: 7)
        : _requestTimeout * _candidateModels.length;
    final Duration perModelCap = useBoundedOcr
        ? const Duration(seconds: 4)
        : _requestTimeout;
    final stopwatch = Stopwatch()..start();

    String lastError = '';
    bool receivedEmptySuccess = false;

    for (final model in _candidateModels) {
      final remaining = totalBudget - stopwatch.elapsed;
      if (remaining <= Duration.zero) {
        if (lastError.isEmpty) {
          lastError =
              'Error generating $label: TimeoutException after ${totalBudget.inSeconds}s';
        }
        break;
      }
      final attemptTimeout = remaining < perModelCap ? remaining : perModelCap;

      final thinkingConfig = isOcr ? _ocrThinkingConfigForModel(model) : null;
      final Map<String, dynamic> genConfig = {
        // Minimize or disable thinking overhead so thinking tokens do not starve OCR output.
        'maxOutputTokens': isOcr ? 1024 : 1500,
        'temperature': isOcr ? 0.0 : 0.7,
        if (thinkingConfig != null) 'thinkingConfig': thinkingConfig,
      };
      final requestBody = jsonEncode({
        'contents': [
          {'role': 'user', 'parts': parts},
        ],
        'generationConfig': genConfig,
      });

      try {
        // Gemini API Auth keys (AQ.*) require the x-goog-api-key header without a ?key= query param.
        final uri = Uri.parse(
          'https://generativelanguage.googleapis.com/v1beta/models/$model:generateContent',
        );
        final headers = {
          'Content-Type': 'application/json',
          'x-goog-api-key': _apiKey,
        };

        final futureRes = _client != null
            ? _client.post(uri, headers: headers, body: requestBody)
            : http.post(uri, headers: headers, body: requestBody);
        final res = await futureRes.timeout(attemptTimeout);

        if (res.statusCode == 200) {
          final data = jsonDecode(utf8.decode(res.bodyBytes));
          final resParts =
              data['candidates']?[0]?['content']?['parts'] as List?;
          final text = resParts
              ?.where((p) => p is Map && p['thought'] != true)
              .map((p) => p['text'] ?? '')
              .join('')
              .trim();
          if (text != null && text.isNotEmpty) {
            return text;
          }
          receivedEmptySuccess = true;
          continue;
        }

        lastError =
            'Error generating $label (${res.statusCode}): ${utf8.decode(res.bodyBytes)}';

        // Stop immediately on credential/permission or invalid API key errors;
        // retry next model on rate-limit, transient server, or model issues.
        if (res.statusCode == 401 ||
            res.statusCode == 403 ||
            (res.statusCode == 400 &&
                (lastError.contains('API_KEY_INVALID') ||
                    lastError.contains('API key not valid')))) {
          return lastError;
        }
      } on SocketException catch (e) {
        return 'Error generating $label: $e';
      } catch (e) {
        lastError = 'Error generating $label: $e';
        if (lastError.contains('SocketException') ||
            lastError.contains('Failed host lookup')) {
          return lastError;
        }
      }
    }

    if (receivedEmptySuccess) {
      return isOcr ? '' : 'No $label generated.';
    }

    return lastError.isNotEmpty ? lastError : 'Failed to generate $label.';
  }

  Future<String> generateQuickQuiz(
    String contentText, {
    List<String>? imagePaths,
  }) => _generate(
    'Act as an expert educator. Based on the following teaching content/slide image, '
        'generate a maximum of 10 multiple-choice questions (MCQs) with 4 options '
        'each (A, B, C, D) and clearly indicate the correct answer.\n\n'
        'Format each question strictly like this example:\n'
        '1. What is the primary function of photosynthesis?\n'
        'A. To absorb water\n'
        'B. To convert light energy into chemical energy\n'
        'C. To release carbon dioxide\n'
        'D. To produce heat\n'
        'Correct Answer: B\n\n'
        'Content:\n$contentText',
    'Quick Quiz',
    imagePaths: imagePaths,
  );

  Future<String> generateHomework(
    String contentText, {
    List<String>? imagePaths,
  }) => _generate(
    'Based on the following lesson content/slide image, create engaging homework '
        'questions or short assignments for students to test their '
        'understanding.\n\nContent:\n$contentText',
    'Homework',
    imagePaths: imagePaths,
  );

  Future<String> generateSummary(
    String contentText, {
    List<String>? imagePaths,
  }) => _generate(
    'Act as an expert educator. Provide a comprehensive, in-depth professional summary '
        '(at least 100 to 150 words) of the topic, core concepts, and detailed teaching talking points '
        'based on the following teaching content/slide image. Ensure the explanation is thorough, clear, '
        'and structured with bullet points so a teacher can easily explain it in depth to students in class.\n\n'
        'Content:\n$contentText',
    'Summary',
    imagePaths: imagePaths,
  );

  Future<String> recognizeHandwriting({
    String? imagePath,
    Uint8List? imageBytes,
    String? language,
  }) async {
    final langInstruction =
        (language != null &&
            language.isNotEmpty &&
            !language.toLowerCase().contains('follow system'))
        ? 'Primary handwriting language is $language. Preserve words in their actual written script (use accurate Devanagari/native script for $language words, and keep numbers or clearly English terms as written). Do NOT transliterate or guess look-alike English letters for non-English script. '
        : 'The handwriting may be English (Latin), Hindi (Devanagari), numbers, or bilingual. Carefully identify the true written script — NEVER force Hindi Devanagari strokes (like shirorekha/matras) into look-alike English letters. Preserve exact words, digits, and line breaks. ';
    final result = (await _generate(
      'Transcribe the handwritten text or notes in this whiteboard image. $langInstruction'
          'Extract ONLY the exact handwritten text, word, or sentence written in the image. '
          'Return strictly the plain text string with zero extra explanation, markdown, or quotation marks. '
          'If no legible text is present, return an empty string.',
      'Handwriting OCR',
      imagePaths: imagePath != null ? [imagePath] : null,
      directBytes: imageBytes != null ? [imageBytes] : null,
    )).trim();

    if (isErrorResponse(result)) return result;

    return result
        .replaceAll(RegExp(r'^```[a-zA-Z0-9_-]*\s*'), '')
        .replaceAll(RegExp(r'\s*```$'), '')
        .trim();
  }

  Future<String> translateWithAi(String prompt) =>
      _generate(prompt, 'Translation');

  Future<String> generateMindMap(String prompt) => _generate(prompt, 'MindMap');
}
